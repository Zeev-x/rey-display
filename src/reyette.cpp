//SFX
void errorScreenEffect(){
  auto sfx = [](int z, int a){
    for (int x = 0; x < a; x++){
      display.invertDisplay(true);
      delay(z);
      display.invertDisplay(false);
      delay(z);
    }
  };

  int S = random(1, 6);
  int F = random(20, 101);
  int X = random(500, 1001);

  sfx(F, S);
  delay(X);
}
